import argparse
import subprocess
import os
import shutil
from Bio import SeqIO

#set up parser
parser = argparse.ArgumentParser(
                    prog='predictor',
                    description='Script that performs the gene prediction of a new assembly using braker3 or galba',
                    epilog='')

parser.add_argument('inputdir',help="path to the pipeline directory generated by assembly.py (the one containing a working directory and results directory) (make sure this is an absolute path)")
parser.add_argument('proteindb',help="path to the database of other snail proteins as an unzipped fasta (make sure this is an absolute path)")
parser.add_argument('cdna_input1',help="path to the forward short read cdna data fastq.gz")
parser.add_argument('cdna_input2',help="path to the reverse short read cdna data fastq.gz")
parser.add_argument('-nr','--norna',action='store_true',help="run gene prediction using GALBA instead of BRAKER3 (input path to galba with the -b flag)")
parser.add_argument('-s', '--snail', help="the name of the snail genome being assembled (default = lmaximus)" )
parser.add_argument('-d', '--dfam', help="path to the dfam tetools singularity file (make sure this is an absolute path) (default = /media/data2/dfam-tetools-latest.sif)")
parser.add_argument('-d15', '--dfam15', help="path to partition 15 of the dfam transposable element database in fasta format (default = /media/data2/gastropoda.fa)")
parser.add_argument('-trf', '--trf_prgm', help="path to the trf executable (make sure this is an absolute path) (if you use conda it will be in the environment prediction under /bin) (default = /home/milan/miniconda3/envs/prediction/bin/trf")
parser.add_argument('-b', '--braker', help="path to the braker singularity (make sure this is an absolute path) (default = /media/data2/braker3.sif)")
parser.add_argument('-c', '--cutoff', help="cutoff for the lengths of the proteins created by braker/galba, proteins under this length are filtered out (default = 150)")
parser.add_argument('-t', '--threads', help="the amount of threads you'd like to use (default = 94)")
parser.add_argument('-sf', '--start_from', help="the step of the assembly to start from, to see the list of steps use -sl")
parser.add_argument('-sl', '--stepslist', action='store_true',help="Showcase a list of steps for the -sf flag")
parser.add_argument('-ba', '--braker_args', help="additional braker/galba arguments")


args=parser.parse_args()
trf=args.trf_prgm
norna=args.norna
assemblydir=args.inputdir
cdna1=args.cdna_input1
cdna2=args.cdna_input2
threads=args.threads
proteindb=args.proteindb
dfam=args.dfam
dfam15=args.dfam15
braker=args.braker
step=args.start_from
sl=args.stepslist
snail=args.snail
ba=args.braker_args
threshold=args.cutoff
if threshold == None:
    threshold=150
threshold=int(threshold)

steplist=["masking","braker"]
if sl:
    print("masking (already the start of the pipeline so will not have any meaningful effect)\nbraker")
    quit()

if ba==None:
    ba=""

if step != None and step not in steplist:
    print("ERROR: please input a valid step to start from (to see a list of possible steps use -sl)")
    quit()


if threads==None:
    threads=94

if snail == None:
    snail="lmaximus"

snail=args.snail.replace(" ","")

if dfam == None:
    dfam="/media/data2/dfam-tetools-latest.sif"

if trf == None:
    trf="/home/milan/miniconda3/envs/prediction/bin/trf"

if braker == None:
    braker="/media/data2/braker3.sif"

if dfam15 == None:
    dfam15="/media/data2/gastropoda.fa"

if os.path.isfile(dfam) == False:
    print(f"ERROR: file: {dfam} does not exist, exiting")
    quit()

if os.path.isfile(dfam15) == False:
    print(f"ERROR: file: {dfam15} does not exist, exiting")
    quit()


if os.path.isdir(assemblydir) == False:
    print(f"ERROR: directory: {asssemblydir} does not exist, exiting")
    quit()

assembly=f"{assemblydir}/results/{snail}_final_assembly_corrected.fasta"

if os.path.isdir(f"{assemblydir}/working_directory/prediction") == False:
    os.mkdir(f"{assemblydir}/working_directory/prediction")

predictdir=f"{assemblydir}/working_directory/prediction"

if step != "braker":
    if os.path.isdir(f"{predictdir}/repeatmodeler") == False:
        os.mkdir(f"{predictdir}/repeatmodeler")
    shutil.copyfile(assembly,f"{predictdir}/repeatmodeler/{snail}_final_assembly_corrected.fasta")
    subprocess.run(f"singularity exec {dfam} BuildDatabase -name {snail} {snail}_final_assembly_corrected.fasta",cwd=f"{predictdir}/repeatmodeler", shell=True)
    subprocess.run(f"singularity exec {dfam} RepeatModeler -threads {threads} -database {snail}",cwd=f"{predictdir}/repeatmodeler",shell=True)
    subprocess.run(f"cat {dfam15} {predictdir}/repeatmodeler/{snail}-families.fa > {predictdir}/repeatmodeler/{snail}+dfam15.fa",shell=True)
    subprocess.run(f"singularity exec {dfam}  RepeatMasker -xsmall -gff  {snail}_final_assembly_corrected.fasta -trf_prgm {trf} -lib {snail}+dfam15.fa -pa {threads}",cwd=f"{predictdir}/repeatmodeler",shell=True)
    masked=f"{predictdir}/repeatmodeler/{snail}_final_assembly_corrected.fasta.masked"
else:
    masked=f"{predictdir}/repeatmodeler/{snail}_final_assembly_corrected.fasta.masked"


if norna:
    if os.path.isdir(f"{predictdir}/galba") == False:
        os.mkdir(f"{predictdir}/galba")
    shutil.copyfile(proteindb,f"{predictdir}/galba/protref.fa")
    shutil.copyfile(masked,f"{predictdir}/galba/masked.fa")
    if os.path.isdir(f"{predictdir}/galba/aug") == False:
        os.mkdir(f"{predictdir}/galba/aug")
    if os.path.isdir(f"{predictdir}/galba/tmp") == False:
        os.mkdir(f"{predictdir}/galba/tmp")
    subprocess.run(f"singularity exec -B {predictdir}/galba/tmp:/tmp {braker} galba.pl --gff3 --threads {threads} --genome=masked.fa --AUGUSTUS_CONFIG_PATH=aug --prot_seq=protref.fa {ba}" ,cwd=f"{predictdir}/galba",shell=True)
    shutil.rmtree(f"{predictdir}/galba/tmp")
    prots=f"{predictdir}/galba/GALBA/galba.aa"
else:
    if os.path.isdir(f"{predictdir}/braker") == False:
        os.mkdir(f"{predictdir}/braker")
    if os.path.isdir(f"{predictdir}/braker/rna") == False:
        os.mkdir(f"{predictdir}/braker/rna")
    shutil.copyfile(cdna1,f"{predictdir}/braker/rna/cdna_1.fastq.gz")
    shutil.copyfile(cdna2,f"{predictdir}/braker/rna/cdna_2.fastq.gz")
    shutil.copyfile(proteindb,f"{predictdir}/braker/protref.fa")
    shutil.copyfile(masked,f"{predictdir}/braker/masked.fa")
    if os.path.isdir(f"{predictdir}/braker/aug") == False:
        os.mkdir(f"{predictdir}/braker/aug")
    if int(threads) > 48:
        brakerthreads=48
    else:
        brakerthreads=threads
    if os.path.isdir(f"{predictdir}/braker/tmp") == False:
        os.mkdir(f"{predictdir}/braker/tmp")
    subprocess.run(f"singularity exec -B {predictdir}/braker/tmp:/tmp {braker} braker.pl --busco_lineage=mollusca --gff --threads {brakerthreads} --genome=masked.fa --AUGUSTUS_CONFIG_PATH=aug --prot_seq=protref.fa --rnaseq_sets_ids=cdna --rnaseq_sets_dir=rna {ba}" ,cwd=f"{predictdir}/braker",shell=True)
    shutil.rmtree(f"{predictdir}/braker/rna")
    prots=f"{predictdir}/braker/braker/braker.aa"

outtext=""

with open(prots) as fasta_file:
    for record in SeqIO.parse(fasta_file, "fasta"):
        if len(record.seq) > threshold:
            outtext += f">{record.id}\n{record.seq.replace('*','')}\n"

with open(f"{assemblydir}/results/{snail}_proteins_filtered.aa","w") as file:
    file.write(outtext)

subprocess.run(f"busco -i {assemblydir}/results/{snail}_proteins_filtered.aa -f -m protein -c {threads} -l mollusca -f -o{assemblydir}/results/{snail}_busco_filtered_proteins", shell=True)

subprocess.run(f"busco -i {prots} -f -m protein -c {threads} -l mollusca -f -o{assemblydir}/results/{snail}_busco_unfiltered_proteins", shell=True)

print("prediction complete, protein file has been added to the results")
